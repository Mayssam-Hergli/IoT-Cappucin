"""Train the EMBER sensor model and export ember_esp32/model.h.
Usage:  python train.py [--data data] [--out ember_esp32/model.h]
Reads data/<label>_*.csv from record_serial.py. Prints metrics, saves
confusion_matrix.png and metrics.txt (for the slides), writes model.h.
"""
import argparse, glob, os, shutil, sys

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, confusion_matrix, precision_recall_fscore_support
from sklearn.preprocessing import StandardScaler

FEATS = ["gas_delta", "gas_slope", "temp_slope", "light_delta", "flicker"]
CLASSES = ["normal", "leak", "fire"]                        # board order
LABEL_OF = {"normal": "normal", "flashlight": "normal", "handheat": "normal", "gas": "leak", "fire": "fire"}
TRAPS = {"flashlight", "handheat"}
DROP_START, SKIP, TRAIN_FRAC, WIN = 10, 10, 0.70, 10       # rows; 1 row = 0.5 s, window = 10 rows

def board_decision(p):
    """Exact candidate rule of the board (contract section 3). p = [normal, leak, fire]."""
    if p[2] >= 0.6: return "fire"
    if p[1] >= 0.5: return "leak"
    if p[2] >= 0.3: return "fire"
    return "normal"

def load(data_dir):
    train, test = [], []
    files = sorted(glob.glob(os.path.join(data_dir, "*.csv")))
    if not files:
        sys.exit(f"No CSV files in {data_dir}/. Record with record_serial.py first.")
    print(f"{'file':32s} {'class':7s} rows  train  test-windows")
    for path in files:
        prefix = os.path.basename(path).split("_")[0].lower()
        if prefix not in LABEL_OF:
            print(f"  skip {path} (unknown prefix '{prefix}')"); continue
        df = pd.read_csv(path)
        df = df.dropna(subset=FEATS).iloc[DROP_START:].reset_index(drop=True)
        df["label"], df["src"] = LABEL_OF[prefix], prefix
        n_train = int(len(df) * TRAIN_FRAC)
        tr = df.iloc[:n_train]
        te = df.iloc[n_train + SKIP:].iloc[::WIN]            # non-overlapping 5 s test windows
        train.append(tr); test.append(te)
        print(f"{os.path.basename(path):32s} {LABEL_OF[prefix]:7s} {len(df):4d} {len(tr):6d} {len(te):6d}")
    if not train:
        sys.exit("No usable files.")
    return pd.concat(train, ignore_index=True), pd.concat(test, ignore_index=True)

def best_rule(train, cls):
    """Best single feature + threshold (feature > t) for one class vs the rest, by F1 on train."""
    y = (train["label"] == cls).values
    best = (0, None, None)
    for f in FEATS:
        x = train[f].values
        for t in np.unique(np.quantile(x, np.linspace(0.02, 0.98, 97))):
            pred = x > t
            tp = (pred & y).sum()
            prec = tp / max(pred.sum(), 1); rec = tp / max(y.sum(), 1)
            f1 = 2 * prec * rec / max(prec + rec, 1e-9)
            if f1 > best[0]:
                best = (f1, f, float(t))
    return best

def report(name, y_true, y_pred, srcs, out):
    acc = accuracy_score(y_true, y_pred)
    p, r, f1, sup = precision_recall_fscore_support(y_true, y_pred, labels=CLASSES, zero_division=0)
    traps = np.isin(srcs, list(TRAPS))
    trap_fa = (np.array(y_pred)[traps] != "normal").mean() if traps.any() else float("nan")
    lines = [f"== {name} ==", f"accuracy        {acc:.3f}"]
    for i, c in enumerate(CLASSES):
        lines.append(f"{c:7s} precision {p[i]:.3f}  recall {r[i]:.3f}  (n={sup[i]})")
    lines.append(f"KEY METRIC fire recall = {r[2]:.3f}   (a missed fire costs lives)")
    lines.append(f"false alarms on traps (flashlight, hand heat) = {trap_fa:.3f}"
                 + ("" if traps.any() else "  (no trap files recorded)"))
    for l in lines: print(l)
    out.extend(lines + [""])
    return confusion_matrix(y_true, y_pred, labels=CLASSES), acc, r[2], trap_fa

def plot_cm(ax, cm, title):
    ax.imshow(cm, cmap="Oranges")
    ax.set_xticks(range(3), CLASSES); ax.set_yticks(range(3), CLASSES)
    ax.set_xlabel("predicted"); ax.set_ylabel("true"); ax.set_title(title)
    for i in range(3):
        for j in range(3):
            ax.text(j, i, cm[i, j], ha="center", va="center", fontsize=14,
                    color="white" if cm[i, j] > cm.max() / 2 else "black")

def write_model_h(path, scaler, clf):
    idx = [list(clf.classes_).index(c) for c in CLASSES]       # classes_ is alphabetical -> reorder
    W, B = clf.coef_[idx], clf.intercept_[idx]
    arr = lambda v: "{" + ", ".join(f"{x:.6f}f" for x in v) + "}"
    if os.path.exists(path):
        shutil.copy(path, path + ".bak")
    with open(path, "w", encoding="utf-8") as f:
        f.write("// model.h — generated by train.py. Classes: normal, leak, fire.\n")
        f.write("// Features: " + ", ".join(FEATS) + "\n#pragma once\n")
        f.write("#define FEAT_N 5\n#define CLASS_N 3\n#define MODEL_READY 1\n\n")
        f.write(f"const float FEAT_MEAN[FEAT_N]  = {arr(scaler.mean_)};\n")
        f.write(f"const float FEAT_SCALE[FEAT_N] = {arr(scaler.scale_)};\n")
        f.write("const float W[CLASS_N][FEAT_N] = {\n" + ",\n".join("  " + arr(w) for w in W) + "\n};\n")
        f.write(f"const float B[CLASS_N]         = {arr(B)};\n")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data")
    ap.add_argument("--out", default=os.path.join("ember_esp32", "model.h"))
    a = ap.parse_args()

    train, test = load(a.data)
    missing = [c for c in CLASSES if c not in set(train["label"])]
    if missing:
        sys.exit(f"Missing classes in the data: {missing}. Record them first.")
    print(f"\ntrain rows {len(train)} | test windows {len(test)}"
          + ("   WARNING: < 20 test windows, record longer (120 s) or a second pass" if len(test) < 20 else "  (>= 20 OK)"))

    scaler = StandardScaler().fit(train[FEATS])
    clf = LogisticRegression(max_iter=1000, class_weight="balanced").fit(scaler.transform(train[FEATS]), train["label"])

    idx = [list(clf.classes_).index(c) for c in CLASSES]
    probs = clf.predict_proba(scaler.transform(test[FEATS]))[:, idx]
    y_model = [board_decision(p) for p in probs]

    # simple-rule baseline: best single feature + threshold per class (learned on train)
    rules = {c: best_rule(train, c) for c in ("fire", "leak")}
    def rule_pred(row):
        if row[rules["fire"][1]] > rules["fire"][2]: return "fire"
        if row[rules["leak"][1]] > rules["leak"][2]: return "leak"
        return "normal"
    y_rule = [rule_pred(r) for _, r in test.iterrows()]

    out = []
    print()
    cm_m, acc_m, fr_m, fa_m = report("EMBER model (logistic regression, board decision rule)", test["label"], y_model, test["src"].values, out)
    print()
    cm_r, acc_r, fr_r, fa_r = report("Simple threshold rule (baseline)", test["label"], y_rule, test["src"].values, out)

    print("\nSimple-rule thresholds (put these in config.py RULE_* for the dashboard comparison):")
    for c, (f1, feat, t) in rules.items():
        line = f"  {c}: {feat} > {t:.3f}   (train F1 {f1:.2f})"
        print(line); out.append(line)

    print("\nSide by side:           model   simple rule")
    for name, m, r in (("accuracy", acc_m, acc_r), ("fire recall", fr_m, fr_r), ("trap false alarms", fa_m, fa_r)):
        line = f"  {name:20s} {m:6.3f}   {r:6.3f}"
        print(line); out.append(line)

    print("\nModel weights (what pushes each class):")
    for c, i in zip(CLASSES, idx):
        print(f"  {c:7s} " + "  ".join(f"{f}={w:+.2f}" for f, w in zip(FEATS, clf.coef_[i])))

    fig, axes = plt.subplots(1, 2, figsize=(11, 4.6))
    plot_cm(axes[0], cm_m, f"EMBER model  (acc {acc_m:.2f}, fire recall {fr_m:.2f})")
    plot_cm(axes[1], cm_r, f"Simple rule  (acc {acc_r:.2f}, fire recall {fr_r:.2f})")
    fig.suptitle(f"Test set: {len(test)} non-overlapping 5 s windows (time-based split)")
    fig.tight_layout(); fig.savefig("confusion_matrix.png", dpi=150)
    with open("metrics.txt", "w", encoding="utf-8") as f:
        f.write(f"test windows: {len(test)}\n\n" + "\n".join(out) + "\n")

    write_model_h(a.out, scaler, clf)
    print(f"\nSaved confusion_matrix.png, metrics.txt and {a.out} (MODEL_READY 1). Flash the board.")

if __name__ == "__main__":
    main()
